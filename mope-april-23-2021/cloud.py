#!/usr/bin/env python3
"""
cloud.py -- run the stack's backend in one container behind one public port (Sevalla, etc.).

Starts, on loopback only:  master server, account server, one region server per enabled region
Then, on 0.0.0.0:$PORT:     services/edge.py cloud  (API + WebSockets at /r/<region-id>)

The archived game client is NOT part of this: players run it on their own machine with
`localstack.py up` and REMOTE_BACKEND_URL pointing here (see DEPLOY_SEVALLA.md).

Environment (all optional):
  PORT                public port (the platform sets it; default 8080)
  PUBLIC_HOST         this backend's public host name, used in /master/client-config urls
                      (on Render, RENDER_EXTERNAL_HOSTNAME is used when this is unset)
  CLOUD_REGIONS       comma-separated region ids to run (default: every enabled region)
  BACKEND_ACCESS_KEY  if set, every request must carry it (X-Backend-Key); players put the
                      same value in REMOTE_BACKEND_KEY
  ACCOUNT_DB_PATH     SQLite path (default data/accounts.sqlite3 -> mount a disk at /app/data)
  plus every setting in .env.example (ACCOUNT_*, CLIENT_*, DEV_*)

If any process exits, everything is stopped and cloud.py exits non-zero so the platform
restarts the container.
"""

from __future__ import annotations

import json
import os
import secrets
import signal
import subprocess
import sys
import time
from pathlib import Path

PROJECT = Path(__file__).resolve().parent
sys.path.insert(0, str(PROJECT))

import localstack  # noqa: E402
from services import common  # noqa: E402

GENERATED = PROJECT / "config" / "_cloud_stack.json"
REMOTE_ONLY_SETTINGS = ("REMOTE_BACKEND_URL",)


def build_config(port: int) -> Path:
    base = json.loads(common.DEFAULT_CONFIG.read_text(encoding="utf-8"))
    base["_comment"] = "Generated by cloud.py at container start; do not edit."
    base["bind_host"] = "127.0.0.1"
    base["public_host"] = (os.environ.get("PUBLIC_HOST", "").strip()
                           or os.environ.get("RENDER_EXTERNAL_HOSTNAME", "").strip()  # set by Render
                           or "backend.invalid")
    base["region_routing"] = "path"
    base["web"]["port"] = port          # the edge takes the web slot, so port clashes are caught
    wanted = [r.strip() for r in os.environ.get("CLOUD_REGIONS", "").split(",") if r.strip()]
    if wanted:
        known = {r["id"] for r in base["regions"]}
        unknown = [r for r in wanted if r not in known]
        if unknown:
            raise SystemExit(f"error: CLOUD_REGIONS has unknown region ids: {', '.join(unknown)}")
        for region in base["regions"]:
            region["enabled"] = region["id"] in wanted
    GENERATED.write_text(json.dumps(base, indent=2), encoding="utf-8")
    return GENERATED


def main() -> int:
    for name in REMOTE_ONLY_SETTINGS:
        if os.environ.get(name):
            print(f"error: {name} is for players' machines, not the hosted backend; unset it", file=sys.stderr)
            return 2
    port = int(os.environ.get("PORT", "8080"))
    config_path = build_config(port)
    try:
        config = common.load_stack_config(config_path)
    except common.ConfigError as exc:
        print(f"error: {exc}", file=sys.stderr)
        return 2
    settings = config["settings"]
    if settings["DEV_ADMIN_ENDPOINTS_ENABLED"] or settings["DEV_TEST_ACCOUNTS_ENABLED"]:
        print("warning: developer endpoints/test accounts are enabled on a PUBLIC backend", file=sys.stderr)
    if not os.environ.get("BACKEND_ACCESS_KEY"):
        print("note: BACKEND_ACCESS_KEY is not set; anyone who knows this URL can use the backend", file=sys.stderr)

    token = secrets.token_hex(16)
    env = dict(os.environ, **{common.TOKEN_ENV: token, "PYTHONUNBUFFERED": "1"})
    backend = [s for s in localstack.services(config) if s.name != "web"]
    edge = localstack.Service("edge", "edge.py", port, ["cloud", "--port", str(port)],
                              f"http://127.0.0.1:{port}/__edge/health")
    procs: list[tuple[localstack.Service, subprocess.Popen]] = []
    stopping = False

    def stop_all(code: int) -> int:
        nonlocal stopping
        stopping = True
        for svc, proc in reversed(procs):
            if proc.poll() is None:
                proc.terminate()
        deadline = time.time() + 10
        for svc, proc in reversed(procs):
            try:
                proc.wait(timeout=max(0.1, deadline - time.time()))
            except subprocess.TimeoutExpired:
                proc.kill()
        return code

    def on_signal(signum, frame):
        print(f"cloud: signal {signum}, stopping", file=sys.stderr, flush=True)
        sys.exit(stop_all(0))

    signal.signal(signal.SIGTERM, on_signal)
    signal.signal(signal.SIGINT, on_signal)

    for svc in backend + [edge]:
        cmd = [sys.executable, str(PROJECT / "services" / svc.script), "--config", str(config_path), *svc.extra]
        proc = subprocess.Popen(cmd, cwd=PROJECT, env=env, stdin=subprocess.DEVNULL)
        procs.append((svc, proc))
        deadline = time.time() + 30
        while not localstack.ready(config, svc):
            if proc.poll() is not None or time.time() > deadline:
                print(f"cloud: {svc.name} failed to start (exit {proc.poll()})", file=sys.stderr, flush=True)
                return stop_all(1)
            time.sleep(0.1)
        print(f"cloud: {svc.name} ready (pid {proc.pid}, port {svc.port})", flush=True)
    regions = sum(1 for s in backend if s.name.startswith("region-"))
    print(f"cloud: backend up on :{port} with {regions} region(s)", flush=True)

    while not stopping:
        for svc, proc in procs:
            if proc.poll() is not None:
                print(f"cloud: {svc.name} exited with {proc.returncode}; stopping everything", file=sys.stderr,
                      flush=True)
                return stop_all(1)
        time.sleep(1)
    return 0


if __name__ == "__main__":
    sys.exit(main())
